"""The OKF bundle (procedural memory) and the ontology terms its concepts read and write.

Ported from the cross-border private equity project's Ontology Grounding extension of OKF v0.2: `reads`, `writes`,
`supports`, procedure `steps` with `performed_by` and `uses`, a generated `# Glossary`, and a mapping that says
where each term lives. Semantic QBRs are checked with the same rules.

    python -m aai.bundle mapping                       (regenerate references/mappings/graph.yaml from aai/graph.py)
    python -m aai.bundle glossary                      (write or refresh every glossary)
    python -m aai.bundle check                         (bundle and semantic QBRs)
    python -m aai.bundle affected aai:ProductMention   (what a term change touches)
"""
import importlib
import json
import os
import re
import sys
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import yaml
from rdflib import OWL, RDF, RDFS, BNode, Graph, Namespace, URIRef
from rdflib.collection import Collection
from rdflib.namespace import SKOS

from . import SOLUTION, STATE
from .graph import NODES, RELS

BUNDLE = SOLUTION / "bundle"
MODEL = SOLUTION / "model" / "aai-model.ttl"
MAPPING = BUNDLE / "references" / "mappings" / "graph.yaml"
AAI = Namespace("https://w3id.org/aai/ontology#")
GLOSSARY = "\n# Glossary\n"
KINDS = {OWL.Class: "class", OWL.ObjectProperty: "relationship", OWL.DatatypeProperty: "attribute"}
# Terms held as a code on a node, or outside the graph, rather than as a same-named node, edge or property.
EXTRA = {
    "aai:hasMetricType": ["`AssetObservation.metricType`"],
    "aai:affects": ["`ExperienceObservation.affectedGroup`"],
    "aai:hasState": ["`ProductStateRecord.state`"],
    "aai:inTaxonomy": ["`IntentConcept.taxonomyVersion`"],
    "aai:dispositionReason": ["the task store, `actions.note`"],
    "aai:Assignment": ["the task store, `assignments`"],
    "aai:assignsWork": ["the task store, `assignments.work_type` and `assignments.work_id`"],
    "aai:assignedTo": ["the task store, `assignments.to_rep`"],
    "aai:acknowledgedAt": ["the task store, `assignments.acknowledged_at`"],
    "aai:Coverage": ["the task store, `coverage`"],
    "aai:coversFor": ["the task store, `coverage.covers_for`"],
    "aai:coveredBy": ["the task store, `coverage.covered_by`"],
}


# ------------------------------------------------------------ ontology

@lru_cache
def ontology() -> Graph:
    g = Graph()
    g.parse(MODEL)
    return g


def curie(iri) -> str:
    return "aai:" + str(iri)[len(str(AAI)):] if str(iri).startswith(str(AAI)) else str(iri)


def to_iri(term: str) -> URIRef:
    return AAI[term.split(":", 1)[1]] if term.startswith("aai:") else URIRef(term)


def version() -> str:
    g = ontology()
    return str(g.value(g.value(predicate=RDF.type, object=OWL.Ontology), OWL.versionInfo))


def kind(term: str):
    types = set(ontology().objects(to_iri(term), RDF.type))
    return next((name for t, name in KINDS.items() if t in types), "code" if types else None)


def _names(node) -> list:
    if isinstance(node, BNode):
        union = ontology().value(node, OWL.unionOf)
        return [curie(n) for n in Collection(ontology(), union)] if union else []
    return [curie(node)] if node else []


def describe(term: str) -> dict:
    g, iri = ontology(), to_iri(term)
    d = {"kind": kind(term), "definition": str(g.value(iri, SKOS.definition) or ""),
         "status": str(g.value(iri, AAI.termStatus) or ""), "steward": str(g.value(iri, AAI.steward) or "")}
    if d["kind"] in ("relationship", "attribute"):
        d["of"] = _names(g.value(iri, RDFS.domain))
        rng = g.value(iri, RDFS.range)
        d["range"] = str(rng).replace("http://www.w3.org/2001/XMLSchema#", "xsd:") if d["kind"] == "attribute" else ", ".join(f"`{n}`" for n in _names(rng))
    return d


# ------------------------------------------------------------ graph mapping

def build_mapping() -> dict:
    """Where each ontology term lives in LadybugDB, read from the schema in aai/graph.py."""
    entries = []
    for spec in NODES:
        table, cols = re.match(r"(\w+)\((.*)\)", spec).groups()
        props = {f"aai:{c.split()[0]}": c.split()[0] for c in cols.split(", ") if kind(f"aai:{c.split()[0]}")}
        entries.append({"term": f"aai:{table}", "node": table, "key": "id", **({"properties": props} if props else {})})
    for spec in RELS:
        name, body = re.match(r"(\w+)\((.*)\)", spec).groups()
        pairs = re.findall(r"FROM (\w+) TO (\w+)", body)
        entries.append({"term": f"aai:{name}", "edge": name, "between": [f"{a} -> {b}" for a, b in pairs]})
    return {"source": "graph", "runtime": "ladybug", "built_by": "aai/graph.py",
            "note": "Generated by `python -m aai.bundle mapping`; do not edit. A mapping says where to look; it is not a query.",
            "mappings": entries}


@lru_cache
def mapping() -> dict:
    return yaml.safe_load(MAPPING.read_text())


def located(term: str) -> list:
    found = []
    for m in mapping()["mappings"]:
        if m["term"] == term:
            found.append(f"a `{m['node']}` node" if "node" in m else
                         f"a `{m['edge']}` edge, " + "; ".join(f"`{p}`" for p in m["between"]))
        if term in m.get("properties", {}):
            found.append(f"`{m['node']}.{m['properties'][term]}`")
    return found + EXTRA.get(term, [])


# ------------------------------------------------------------ bundle concepts

@dataclass
class Concept:
    id: str
    path: Path
    meta: dict
    body: str


def read(path: Path, root: Path = BUNDLE) -> Concept:
    _, front, body = path.read_text().split("---\n", 2)
    return Concept(str(path.relative_to(root)).removesuffix(".md"), path, yaml.safe_load(front), body)


@lru_cache
def concepts() -> dict:
    return {c.id: c for c in (read(p) for p in sorted(BUNDLE.rglob("*.md")) if p.name != "index.md")}


def resolve(path: str) -> Path:
    return BUNDLE / path.lstrip("/")


def glossary(c: Concept) -> str:
    lines = []
    for term in dict.fromkeys(c.meta.get("reads", []) + c.meta.get("writes", [])):
        d = describe(term)
        meaning = [d["definition"]]
        if "of" in d:
            meaning.append("Of " + ", ".join(f"`{o}`" for o in d["of"]) + ".")
            meaning.append(f"Value: {d['range']}." if d["kind"] == "relationship" else f"Value: `{d['range']}`.")
        facts = [d["kind"], d["status"], f"steward: {d['steward']}" if d["steward"] else None]
        lines += [f"- **`{term}`** ({'; '.join(f for f in facts if f)})",
                  f"  - Meaning: {' '.join(m for m in meaning if m) or 'No definition in the ontology.'}",
                  f"  - In the graph: {'; '.join(located(term)) or 'not held'}."]
    here = c.path.parent
    head = (f"Meanings from ontology version {version()}, [{MODEL.name}]({os.path.relpath(MODEL, here)}). "
            f"Locations from the graph mapping, [{MAPPING.name}]({os.path.relpath(MAPPING, here)}). "
            "For the terms in `reads` and `writes`. Generated by `aai/bundle.py`; do not edit.")
    return "\n".join([head, ""] + lines)


def write_glossary(c: Concept):
    body = c.path.read_text().split(GLOSSARY)[0].rstrip("\n")
    c.path.write_text(f"{body}\n{GLOSSARY}\n{glossary(c)}\n")


def _implemented(ref: str) -> bool:
    file, _, attr = ref.partition("#")
    if not (SOLUTION / file).exists():
        return False
    obj = importlib.import_module(file.removesuffix(".py").replace("/", "."))
    for part in attr.split("."):
        obj = getattr(obj, part, None)
    return obj is not None


def check(semantic_qbrs: Path = STATE / "semantic-qbr") -> list:
    problems = []
    index = yaml.safe_load((BUNDLE / "index.md").read_text().split("---\n", 2)[1]).get("ontology", {})
    if index.get("prefix") != "aai" or index.get("namespace") != str(AAI):
        problems.append(f"index: ontology prefix and namespace are not aai and {AAI}")
    if not (BUNDLE / index.get("resource", "missing")).resolve().exists():
        problems.append("index: the ontology resource does not exist")
    if mapping() != build_mapping():
        problems.append("references/mappings/graph.yaml is out of date with aai/graph.py; run `python -m aai.bundle mapping`")
    found = list(concepts().values())
    found += [read(p, semantic_qbrs) for p in sorted(semantic_qbrs.glob("*.md"))] if semantic_qbrs.exists() else []
    for c in found:
        if not c.meta.get("type"):
            problems.append(f"{c.id}: no type")
        for term in c.meta.get("reads", []) + c.meta.get("writes", []):
            if kind(term) is None:
                problems.append(f"{c.id}: {term} is not in the ontology")
        uses = [u for s in c.meta.get("steps", []) for u in s.get("uses", [])]
        uses += [c.meta["procedure"]["resource"]] if "procedure" in c.meta else []
        for u in uses:
            if not resolve(u).exists():
                problems.append(f"{c.id}: {u} does not resolve")
        if "implemented_by" in c.meta and not _implemented(c.meta["implemented_by"]):
            problems.append(f"{c.id}: {c.meta['implemented_by']} does not exist")
        if c.path.is_relative_to(BUNDLE) and (c.meta.get("reads") or c.meta.get("writes")):
            if GLOSSARY not in c.body:
                problems.append(f"{c.id}: no glossary; run `python -m aai.bundle glossary`")
            elif c.body.split(GLOSSARY)[1].strip() != glossary(c):
                problems.append(f"{c.id}: glossary is out of date with the ontology or the mapping")
    return problems


def affected(term: str) -> dict:
    direct = sorted(c.id for c in concepts().values() if term in c.meta.get("reads", []) + c.meta.get("writes", []))
    steps = [{"procedure": c.id, "step": s["id"], "title": s["title"]} for c in concepts().values()
             for s in c.meta.get("steps", []) if {u.lstrip("/").removesuffix(".md") for u in s.get("uses", [])} & set(direct)]
    return {"term": term, "concepts": direct, "steps": steps}


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "mapping":
        MAPPING.parent.mkdir(parents=True, exist_ok=True)
        MAPPING.write_text("# " + build_mapping()["note"] + "\n" + yaml.safe_dump(build_mapping(), sort_keys=False, width=200))
    elif cmd == "glossary":
        for c in concepts().values():
            if c.meta.get("reads") or c.meta.get("writes"):
                write_glossary(c)
    elif cmd == "affected":
        print(json.dumps(affected(sys.argv[2]), indent=2))
    else:
        found = check()
        print("\n".join(found) if found else f"Bundle is consistent: {len(concepts())} concepts, ontology v{version()}.")
        sys.exit(1 if found else 0)
